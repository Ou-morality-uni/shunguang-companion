"""Export contracts without starting the server or opening the user database."""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from backend.app.constants import MAX_MESSAGE_LENGTH
from backend.app.main import app

target = ROOT / 'frontend' / 'openapi.json'
content = json.dumps(app.openapi(), ensure_ascii=False, indent=2, sort_keys=True) + '\n'
limits = ROOT / 'frontend/src/generated/limits.ts'
limits_content = f'// Generated by scripts/export-openapi.py. Do not edit.\nexport const MAX_MESSAGE_LENGTH = {MAX_MESSAGE_LENGTH};\n'
if '--check' in sys.argv:
    if (
        not target.exists()
        or target.read_text(encoding='utf-8') != content
        or not limits.exists()
        or limits.read_text(encoding='utf-8') != limits_content
    ):
        raise SystemExit('API contract changed. Run scripts/export-openapi.py and npm run gen:api.')
else:
    target.write_text(content, encoding='utf-8')
    limits.parent.mkdir(parents=True, exist_ok=True)
    limits.write_text(limits_content, encoding='utf-8')
